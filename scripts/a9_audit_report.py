"""Amendment 9 audit report: false acceptance with vs without the receipt ledger, paired on the same episodes (Aya
Expanse 32B, bf16), plus the 8B grounded run. Exact McNemar on discordant pairs. CPU.

    python scripts/a9_audit_report.py > results/judge/grounded_audit.md
"""
import json
from math import comb

from actionproof.eval.stats import wilson


def rows(tag, judge):
    return {(r["source"], r["task_id"], r["fault"], i): r for i, r in
            enumerate(json.loads(l) for l in open(f"results/judge/{tag}__{judge}.jsonl"))}


def mcnemar(b, c):
    n = b + c
    return 1.0 if n == 0 else min(1.0, 2 * sum(comb(n, k) for k in range(min(b, c) + 1)) / 2 ** n)


print("# Grounded judge audit (Amendment 9)\n\nGenerated by `scripts/a9_audit_report.py` from `results/judge/<tag>__<judge>.jsonl`. "
      "Same 815-episode pool as the original audit (476 false completions, G = 0; 339 true completions, G = 1). "
      "`ledger_fail`: a write did not commit, or committed partially, so the ledger alone shows the failure. "
      "Acceptance = verdict COMPLETE. Paired on the same episodes; unparsed verdicts dropped pairwise.\n")
print("| judge | episodes | without ledger | with ledger | change | discordant (fixed / broken) | McNemar p |\n|---|---|---|---|---|---|---|")
for judge, name in (("auditkit_tc", "AuditKIT TaskCompletion, Aya 32B"), ("llm_judge", "our judge prompt, Aya 32B")):
    t, g = rows("aya32b_t", judge), rows("aya32b_grounded", judge)
    for label, sel in (("false completions, ledger shows it", lambda r: r["G"] == 0 and r["ledger_fail"]),
                       ("false completions, other causes", lambda r: r["G"] == 0 and not r["ledger_fail"]),
                       ("true completions (should accept)", lambda r: r["G"] == 1)):
        ks = [k for k in t if sel(t[k]) and t[k]["score"] is not None and g[k]["score"] is not None]
        a0 = sum(t[k]["score"] == 1.0 for k in ks); a1 = sum(g[k]["score"] == 1.0 for k in ks)
        fixed = sum(t[k]["score"] == 1.0 and g[k]["score"] != 1.0 for k in ks)
        broke = sum(t[k]["score"] != 1.0 and g[k]["score"] == 1.0 for k in ks)
        n = len(ks)
        print(f"| {name}: {label} | {n} | {a0 / n:.3f} | {a1 / n:.3f} | {100 * (a1 - a0) / n:+.1f} pp | {fixed} / {broke} | {mcnemar(fixed, broke):.2g} |")
print("\nAya Expanse 8B with the ledger (no paired transcript-only re-run; its original audit accepted 100% under both prompts):\n")
d = json.load(open("results/judge/aya8b_grounded__summary.json"))
for k, name in (("aya8b_grounded__auditkit_tc", "AuditKIT TaskCompletion"), ("aya8b_grounded__llm_judge", "our judge prompt")):
    x = d[k]["ALL|ledger_fail=True|FAR"]; y = d[k]["ALL|TAR"]
    print(f"- {name}: false acceptance where the ledger shows the failure {x['rate']:.3f} (n = {x['n']}); true acceptance {y['rate']:.3f}")
