"""Track 3 agentic-trajectory metrics for the A12 models, from the confirmatory summaries and the latency files:
per split and model, verified completion (VSC) next to claimed success (report "completed"), false success,
tool-call validity, mean calls per episode; batch-1 latency where measured (proc_dev, seed 0 and the warm start).
    python scripts/track3_metrics.py --out results/s2/track3_metrics
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="results/s2/track3_metrics")
    a = ap.parse_args()
    rows = []
    for f in sorted((ROOT / "results/eval/a12/conf").glob("*.summary.json")):
        s = json.loads(f.read_text())
        tag, split = f.name.replace(".summary.json", "").split("__neutral__")
        claimed = s["vsc"] + s["false_success"]  # report completed = verified completion + false success
        rows.append({"model": tag.replace("a12_proc_", ""), "split": split, "n": s["n"], "verified_completion": s["vsc"],
                     "claimed_success": claimed, "false_success": s["false_success"],
                     "tool_call_validity": s["tool_call_validity"], "mean_calls": s["mean_calls"]})
    lat = {}
    for f in (ROOT / "results/s2").glob("latency_*.json"):
        d = json.loads(f.read_text())
        if "seconds_per_episode" in d:
            lat[d["tag"]] = d["seconds_per_episode"]
    gw = json.loads((ROOT / "results/s2/latency_gateway.json").read_text())["by_mode"]
    res = {"by_model_split": rows, "latency_batch1_proc_dev": lat, "gateway_overhead_ms_per_call": gw}
    out = ROOT / a.out
    out.with_suffix(".json").write_text(json.dumps(res, indent=2))
    md = ["# Track 3 metrics (A12 models, confirmatory splits)", "",
          "Generated by `scripts/track3_metrics.py`. Claimed success = share of episodes reported `completed`; verified "
          "completion = goal met in the final state and reported `completed`.", "",
          "| model | split | n | verified completion | claimed success | false success | tool-call validity | calls / episode |",
          "|---|---|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: (r["split"], r["model"])):
        md.append(f"| {r['model']} | {r['split']} | {r['n']} | {r['verified_completion']:.3f} | {r['claimed_success']:.3f} | "
                  f"{r['false_success']:.3f} | {r['tool_call_validity']:.3f} | {r['mean_calls']:.2f} |")
    md += ["", "Batch-1 latency, proc_dev (40 tasks, L40S), seconds per episode:", "", "| model | mean | p50 | p95 |",
           "|---|---|---|---|"]
    for k, v in sorted(lat.items()):
        md.append(f"| {k} | {v['mean']:.2f} | {v['p50']:.2f} | {v['p95']:.2f} |")
    md += ["", "Gateway overhead per tool call (in-process, CPU, scripted agent), milliseconds:", "",
           "| mode | mean | p50 | p95 |", "|---|---|---|---|"]
    for k, v in gw.items():
        md.append(f"| {k} | {v['mean']:.3f} | {v['p50']:.3f} | {v['p95']:.3f} |")
    out.with_suffix(".md").write_text("\n".join(md) + "\n")
    print("\n".join(md[:8] + md[-14:]))


if __name__ == "__main__":
    main()
