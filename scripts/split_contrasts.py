"""Per-split paired VSC contrasts between v2 arms (ARTICLE §5 table), both seeds averaged per task, task bootstrap 10k (CPU).

    python scripts/split_contrasts.py > results/a4/split_contrasts.md
"""
import json
import random

ARMS = {"pcstr_d": ["grpo_tiny_v2_pcstr_d_s0", "grpo_tiny_v2_pcstr_d_s1"], "outcome": ["grpo_tiny_v2_outcome_s0", "grpo_tiny_v2_outcome_s1"],
        "tool_trust": ["grpo_tiny_v2_tool_trust_s0", "grpo_tiny_v2_tool_trust_s1"]}


def per_task(runs, split):
    tabs = [{json.loads(l)["task_id"]: json.loads(l)["vsc"] for l in open(f"results/eval/r3/{r}__neutral__{split}.jsonl")} for r in runs]
    return {t: sum(d[t] for d in tabs) / len(tabs) for t in tabs[0]}


def contrast(a, b, splits, rng):
    d = []
    for sp in splits:
        A, B = per_task(ARMS[a], sp), per_task(ARMS[b], sp)
        d += [A[t] - B[t] for t in A]
    m = sum(d) / len(d)
    bs = sorted(sum(rng.choice(d) for _ in d) / len(d) for _ in range(10_000))
    return m, bs[250], bs[9749], len(d)


print("# Per-split VSC contrasts, v2 arms (dev splits; both seeds averaged per task; task bootstrap 10k, seed 0)\n")
print("Generated by `scripts/split_contrasts.py`.\n\n| contrast | pooled (test_iid + test_ood_fault) | test_iid | test_ood_fault |\n|---|---|---|---|")
for a, b in (("pcstr_d", "tool_trust"), ("outcome", "tool_trust"), ("pcstr_d", "outcome")):
    cells = []
    for sp in (("test_iid", "test_ood_fault"), ("test_iid",), ("test_ood_fault",)):
        m, lo, hi, n = contrast(a, b, sp, random.Random(0))
        cells.append(f"{m*100:+.2f} pp [{lo*100:+.1f}, {hi*100:+.1f}] (n={n})")
    print(f"| {a} − {b} | " + " | ".join(cells) + " |")
