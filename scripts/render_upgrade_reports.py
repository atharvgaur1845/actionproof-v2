"""Render the R1 (capability retention) and J1 (judge committee) reports from their result files only.
Writes docs/upgrade/CAPABILITY_RETENTION.md and docs/upgrade/JUDGES.md. Re-run after any result changes.
    python scripts/render_upgrade_reports.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EPS = [("ifeval_prompt_strict", "IFEval prompt strict"), ("bfcl_nonlive_ast", "BFCL non-live AST"),
       ("bfcl_live_ast", "BFCL live AST"), ("bfcl_irrelevance", "BFCL irrelevance"), ("bfcl_live_irrelevance", "BFCL live irrelevance")]
ROWS = [("warm_vs_base", "SFT warm start − base (1 model each)"), ("a12_rv_vs_warm", "State-reward GRPO − warm (5)"),
        ("a12_ra_vs_warm", "Acknowledgement-reward GRPO − warm (5)"), ("rsc_vs_warm", "Recovery-start GRPO − warm (5)"),
        ("control_vs_warm", "Class-matched control − warm (5)"), ("ackonly_vs_warm", "Acknowledgement-only starts − warm (5)"),
        ("sr1_vs_warm", "Tool-name randomisation − warm (3)"), ("s1warm_vs_base", "Stage 1 warm start − base"),
        ("s1_pcstr_d_vs_warm", "Stage 1 PCSTR-d − Stage 1 warm (2)"), ("s1_tool_trust_vs_warm", "Stage 1 tool-trust − Stage 1 warm (2)"),
        ("sr1_vs_rsc", "Tool-name randomisation − recovery-start (3 vs 5)")]


def fmt(x) -> str:
    return "—" if x is None else f"{x:.3f}"


def f(x: float) -> str:
    return f"{x:+.3f}".replace("-", "−")


def retention() -> str:
    d = json.loads((ROOT / "results/r1/r1_summary.json").read_text())
    C = d["contrasts"]
    abs_rows = []
    for tag in ("base", "warm_start", "s1_warm_start"):
        s = json.loads((ROOT / f"results/r1/score/{tag}.summary.json").read_text())
        abs_rows.append(f"| `{tag}` | " + " | ".join(f"{s[e]:.3f}" for e, _ in EPS) + f" | {s['bfcl_format_fail_rate']:.3f} | {s['over_length_dropped']} |")
    L = ["# Capability retention (R1): does ProcureSim training cost general ability?", "",
         "Generated by `scripts/render_upgrade_reports.py` from `results/r1/r1_summary.json` and `results/r1/score/`; do not edit by hand.",
         "Registration: `PREREGISTRATION_R1.md` (deviation D-R1-1, before any analysed output). Official checkers: bfcl-eval 2026.3.23 "
         "(BFCL v4, prompting mode), lm-eval 0.4.13 (IFEval). 35 models generated once, greedy, 8,192-token context.", "",
         "## Registered verdicts", "",
         "| Hypothesis | Result | Verdict |", "|---|---|---|"]
    for e, x in d["H1"].items():
        L.append(f"| H1 warm start − base, {e} | {f(x['delta'])} [{f(x['ci95'][0])}, {f(x['ci95'][1])}] | {'supported' if x['supported'] else 'not supported'} |")
    for k, x in d["H2"].items():
        L.append(f"| H2 (primary) non-inferiority, {k} | {f(x['delta'])} [{f(x['ci95'][0])}, {f(x['ci95'][1])}], Holm p {x['holm_p']:.4f} | {'non-inferior (supported)' if x['noninferior'] else 'not shown'} |")
    for k, x in d["H3"].items():
        L.append(f"| H3 irrelevance falls, {k} | {f(x['delta'])} [{f(x['ci95'][0])}, {f(x['ci95'][1])}], Holm p {x['holm_p']:.3f} | {'supported' if x['supported'] else 'not supported'} |")
    L += ["", "## Absolute scores of the reference models", "",
          "| Model | " + " | ".join(n for _, n in EPS) + " | BFCL format failures | Over-length dropped |",
          "|---|" + "---|" * (len(EPS) + 2)] + abs_rows
    L += ["", "## Every contrast (Δ, 95% paired task bootstrap; reference value in brackets)", "",
          "| Contrast | " + " | ".join(n for _, n in EPS) + " |", "|---|" + "---|" * len(EPS)]
    for k, lab in ROWS:
        cells = []
        for e, _ in EPS:
            x = C.get(f"{k}:{e}")
            cells.append("—" if not x else f"{f(x['delta'])} [{f(x['ci95'][0])}, {f(x['ci95'][1])}] ({x['ref_value']:.3f})")
        L.append(f"| {lab} | " + " | ".join(cells) + " |")
    L += ["", "## Reading", "",
          "- **No trained arm shows a measurable loss.** Across every arm and endpoint the most negative point estimate is "
          "−0.012 (Stage 1 PCSTR-d, BFCL live irrelevance). Every procurement-study interval stays above −0.024 "
          "(lowest: acknowledgement-reward GRPO, IFEval). The only lower bound past −0.03 is Stage 1 PCSTR-d on BFCL live "
          "calls (−0.032, two seeds, point estimate −0.004). The primary non-inferiority test passes for both registered arms "
          "on both benchmarks.",
          "- The SFT warm start does not lose either (H1 not supported; point estimates are slightly positive).",
          "- Low abstention on BFCL irrelevance is a **property of the base model** (it calls some function on most items where none "
          "fits), not something training introduced (H3 not supported).",
          "- Tool-name randomisation (SR1) does not improve calls on BFCL's unseen schemas either (intervals include 0), consistent "
          "with its failure on the renamed ProcureSim API.",
          "- Why so little drift: LoRA r16 adapters, KL β = 0.02, 200 GRPO steps; ProcureSim's tool format is plain text, not the "
          "BFCL call syntax, so training does not overwrite it.",
          "- Scope: single-turn function calling and instruction following. Stateful multi-turn retention is R1-T (τ-bench), "
          "reported separately. Mitigations (registered conditional, §7) were not needed.", ""]
    return "\n".join(L)


def judges() -> str:
    d = json.loads((ROOT / "results/j1/j1_summary.json").read_text())
    cb = [v["goal_met=True"]["p_yes_given_claim"] for v in d["claim_bias"].values()]
    names = {"gemma": "Gemma 4 31B", "qwen": "Qwen3 235B-A22B", "gptoss": "gpt-oss-120b", "deepseek": "DeepSeek V3.2"}
    L = ["# LLM judge committee (J1): can independent judges see a silent write failure?", "",
         "Generated by `scripts/render_upgrade_reports.py` from `results/j1/j1_summary.json`; do not edit by hand. Registration: "
         "`PREREGISTRATION_J1.md`; rubric `evaluation/llm_judge_committee/rubric.md`; every reply in "
         "`evaluation/llm_judge_committee/outputs/`. Ground truth: the SQLite verifier.", "",
         "## Registered verdicts", ""]
    h1 = d["J-H1"]
    L.append(f"- **J-H1 (judges fooled on unverifiable failures): {'supported' if h1['supported'] else 'not supported'}.** "
             + "; ".join(f"{names[j]} {v['fooled']}/{v['n']}" for j, v in h1["per_judge"].items()) + " answered 'it happened'.")
    h2 = d["J-H2"]
    L.append(f"- **J-H2 (snapshot accuracy ≥ 0.90 for 3 of 4): {'supported' if h2['supported'] else 'not supported'}.** "
             + "; ".join(f"{names[j]} {v['accuracy']:.3f} [{v['wilson95'][0]:.3f}, {v['wilson95'][1]:.3f}]" for j, v in h2["per_judge"].items()) + ".")
    for view in ("transcript", "transcript_state"):
        b = d[f"main:{view}"]
        L += ["", f"## Main set (660 cases), view `{view}`", "",
              "| Judge | Coverage | Selective accuracy | Accuracy (abstain = wrong) | False-positive rate | κ | Q3 false-success recall | Q3 precision | Parse rate | Median latency (s) | $ per 1,000 |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
        for j, v in b["judges"].items():
            q, r = v["q1_vs_goal_met"], v["q3_vs_false_success"]
            L.append(f"| {names[j]} | {fmt(q['coverage'])} | {fmt(q['selective_accuracy'])} | {fmt(q['accuracy_abstain_wrong'])} | {fmt(q['fpr'])} | "
                     f"{fmt(q['kappa'])} | {fmt(r['recall'])} | {fmt(r['precision'])} | {fmt(v['parse_rate'])} | {v['latency_median_s']} | {v['cost_per_1000_usd']:.3f} |")
        for k, v in b["committee"].items():
            L.append(f"| Committee ({k}) | {fmt(v['coverage'])} | {fmt(v['selective_accuracy'])} | "
                     f"{fmt(v['accuracy_abstain_wrong'])} | {fmt(v['fpr'])} | {fmt(v['kappa'])} | | | | | |")
        L.append(f"\nInter-judge Fleiss κ on Q1: {b['fleiss_kappa_q1']:.3f}. Cases where all four judges contradict the verifier: "
                 f"{len(b['all_four_contradict_verifier'])}.")
    s = d["prompt_sensitivity"]
    L += ["", "## Prompt sensitivity (v1 vs paraphrased v2, transcript view)", "",
          "| Judge | Cases | Q1 agreement | κ |", "|---|---|---|---|"]
    L += [f"| {names[j]} | {v['n']} | {v['agreement_q1']:.3f} | {v['kappa_q1']:.3f} |" for j, v in s.items()]
    L += ["", "## Accuracy by fault class and language (transcript view, selective)", "",
          "| Judge | " + " | ".join(sorted(next(iter(d["by_fault"].values())))) + " | English | Hindi + Hinglish |",
          "|---|" + "---|" * (len(next(iter(d["by_fault"].values()))) + 2)]
    for j, v in d["by_fault"].items():
        L.append(f"| {names[j]} | " + " | ".join("—" if v[c] is None else f"{v[c]:.2f}" for c in sorted(v)) +
                 f" | {d['by_lang'][j]['en']:.2f} | {d['by_lang'][j]['hi+hinglish']:.2f} |")
    L += ["", "## Reading", "",
          "- **Warned judges do not get fooled; they abstain.** With the rubric sentence that an \"ok\" reply is not proof, no judge "
          "accepted more than 1 of 120 unverifiable failures. The price is coverage: they decline about 40–57% of cases, catch only about "
          "a third of false-success claims (Q3 recall), and confirm only "
          "CONFIRM_RANGE of the episodes that genuinely completed. A warned "
          "transcript-only judge is safe but cannot certify outcomes. Addendum 1 tests whether the warning sentence is what does this.",
          "- **A database snapshot does not make judges verifier-grade.** Gemma reaches 0.989; two families stay near 0.89. "
          "Majority voting (0.897) does not beat the best single judge.",
          "- **Systematic bias found:** all four judges misread a refunded duplicate (payment, duplicate, refund rows: net one payment) "
          "as 'paid twice' — 4 cases where every judge contradicts the verifier, which is correct under the documented "
          "transaction semantics. Two-family errors concentrate on partial and duplicate cases.",
          "- **Prompt sensitivity is large except for Gemma** (κ 0.96 vs 0.49–0.65).",
          "- Human calibration: labels pending (one annotator; the author)." if not d.get("human") else
          f"- Human calibration: {d['human']['n']} cases, one annotator.", ""]
    return "\n".join(L).replace("CONFIRM_RANGE", f"{min(cb):.0%}–{max(cb):.0%}")


def main() -> None:
    (ROOT / "docs/upgrade/CAPABILITY_RETENTION.md").write_text(retention())
    (ROOT / "docs/upgrade/JUDGES.md").write_text(judges())
    print("written")


if __name__ == "__main__":
    main()
