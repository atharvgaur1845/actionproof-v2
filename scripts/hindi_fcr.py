"""Why PCSTR-d has FCR 0.62 on test_iid_hi (vs 0.88-1.00 elsewhere): cross-tab of its G=0 Hindi episodes by fault,
Hindi report status, and the same task's English outcome (results/eval/r3 test_iid, seed 0). CPU.

    python scripts/hindi_fcr.py > results/eval/transfer/hindi_fcr.md
"""
import json
from collections import Counter

from actionproof.bench.generator import make_split

T = {t.task_id: t for t in make_split("test_iid_hi")}
hi = [json.loads(l) for l in open("results/eval/transfer/grpo_v2_pcstr_d__neutral__test_iid_hi.jsonl")]
en = {json.loads(l)["task_id"]: json.loads(l) for l in open("results/eval/r3/grpo_tiny_v2_pcstr_d_s0__neutral__test_iid.jsonl")}
c = Counter()
for e in hi:
    if e["verdict"].get("G"):
        continue
    ee = en[e["task_id"].replace("_hi", "")]
    c[("+".join(T[e["task_id"]].meta["faults"]) or "benign", (e.get("report") or {}).get("status"),
       "succeeds" if ee["verdict"].get("G") else "fails")] += 1
esc = sum(v for k, v in c.items() if k[1] == "escalated")
esc_en_ok = sum(v for k, v in c.items() if k[1] == "escalated" and k[2] == "succeeds")
print("# PCSTR-d, Hindi test_iid: where the low false-completion rate comes from\n\n"
      "Generated by `scripts/hindi_fcr.py`. Episodes with G = 0 (goal not met), n = %d.\n\n"
      "| fault | Hindi report | same task in English | episodes |\n|---|---|---|---|" % sum(c.values()))
for (f, s, x), v in sorted(c.items(), key=lambda kv: -kv[1]):
    print(f"| {f} | {s} | {x} | {v} |")
print(f"\n{esc} of the G = 0 Hindi episodes end in `escalated` (summary: the refund is ineligible); the same task succeeds "
      f"in English in {esc_en_ok} of them. The lower FCR is premature escalation on eligible refunds, not more honest "
      "reporting of failures.")
