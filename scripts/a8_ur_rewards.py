"""What does each reward pay on an unrecoverable refund? (CPU; exploratory.)

Unrecoverable refund tasks (`e_unrecoverable`, fault on `issue_refund`, never commits): G = 0 always, but P and V are
not zero when the agent goes on to write the audit note and close the ticket. Real episodes are grouped by behaviour:
`stop` = no audit-note / close-ticket write after the last refund attempt; `continue` = at least one. Each group's
mean reward is reported under every arm (from the stored verifier verdicts), with the report status.

    python scripts/a8_ur_rewards.py results/raw/a6/*__e_unrecoverable.jsonl results/eval/a7/plain/*__e_unrecoverable.jsonl \
        > results/a8/ur_rewards.md
"""
from __future__ import annotations

import json
import statistics
import sys
from collections import defaultdict
from types import SimpleNamespace

from actionproof.rewards import a6_rewards as A6
from actionproof.rewards.a7_rewards import pcstr_d_noFunder_score
from actionproof.rewards.pcstr import pcstr_score

ARMS = {
    "pcstr_d": lambda v: pcstr_score(v, disclosure=True),
    "noreport": A6.pcstr_d_noreport_score,
    "noND": A6.pcstr_d_noND_score,
    "noFunder": pcstr_d_noFunder_score,
    "outcome": lambda v: float(v.P == 1 and v.I == 0),
}


def behaviour(r: dict) -> str | None:
    if (r.get("a4") or {}).get("fault_tool") != "issue_refund":
        return None
    t = [s for s in r["trace"] if not s.get("by")]
    last = max((i for i, s in enumerate(t) if s["tool"] == "issue_refund"), default=None)
    if last is None:
        return None
    go_on = any(s["tool"] in ("add_audit_note", "close_ticket") for s in t[last + 1:])
    rep = r.get("report") or {}
    status = rep.get("status") if isinstance(rep, dict) else rep
    return f"{'continue' if go_on else 'stop'}, report {status if status in ('completed', 'failed') else 'other/none'}"


def main() -> None:
    cells = defaultdict(list)
    for p in sys.argv[1:]:
        for line in open(p):
            r = json.loads(line)
            b = behaviour(r)
            if b:
                cells[b].append(SimpleNamespace(**r["verdict"]))
    print("# Rewards on unrecoverable refunds, by behaviour (exploratory)\n")
    print("Generated by `scripts/a8_ur_rewards.py`; refund-UR episodes pooled over the input files (all models, both "
          "schemas). Mean reward under each arm from the stored verdicts; G = 0 in every episode.\n")
    print("| behaviour | episodes | mean P | mean V | " + " | ".join(ARMS) + " |")
    print("|---|---|---|---|" + "---|" * len(ARMS))
    for b in sorted(cells):
        vs = cells[b]
        print(f"| {b} | {len(vs)} | {statistics.mean(v.P for v in vs):.2f} | {statistics.mean(v.V for v in vs):.2f} | "
              + " | ".join(f"{statistics.mean(fn(v) for v in vs):+.3f}" for fn in ARMS.values()) + " |")


if __name__ == "__main__":
    main()
