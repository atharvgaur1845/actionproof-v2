"""Post-write refund verification split by the refund's key format (CPU; exploratory, not registered).

The corrected battery (results/a7/battery_v2.md) shows that on identical prefixes cut from the demonstrator's template
(prefix d: right after a refund issued with key `refund-<order>`), every model reads next, the warm start and the ack
arm included. This table asks whether the same holds in the models' own rollouts: per episode with a success-acked
refund, is the refund followed by a read of the order (`a4_metrics.pwv`), split by whether the first refund used the
demonstrator's key format (the H7-3 marker)?

    python scripts/a7_key_vs_read.py results/raw/a6 > results/a7/key_vs_read.md
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

from actionproof.eval.a4_metrics import pwv

MODELS = ("init_a6", "a6_pcstr_d_s0", "a6_pcstr_d_noreport_s0", "a6_pcstr_d_noND_s0", "a6_outcome_s0",
          "a6_ack_outcome_s0")
SPLITS = ("test_iid", "e_seen_refund")


def _args(s: dict) -> dict:
    return s.get("args") if isinstance(s.get("args"), dict) else {}


def main() -> None:
    root = Path(sys.argv[1] if len(sys.argv) > 1 else "results/raw/a6")
    print("# Refund read-back by refund key format (exploratory)\n")
    print("Generated by `scripts/a7_key_vs_read.py`. Episodes with a success-acked refund; read = `a4_metrics.pwv`.\n")
    print("| model | split | demonstrator key: read / n | other key: read / n |")
    print("|---|---|---|---|")
    tot = Counter()
    for m in MODELS:
        for split in SPLITS:
            p = root / f"{m}__neutral__{split}.jsonl"
            if not p.exists():
                continue
            c = Counter()
            for line in open(p):
                r = json.loads(line)
                t = [s for s in r["trace"] if not s.get("by")]
                ref = next((s for s in t if s["tool"] == "issue_refund"), None)
                v = pwv(r["trace"], "issue_refund")
                if ref is None or v is None:
                    continue
                demo = _args(ref).get("idempotency_key") == f"refund-{_args(ref).get('order_id')}"
                c[demo, v] += 1
            tot.update(c)
            print(f"| {m} | {split} | {c[True, True]} / {c[True, True] + c[True, False]} | "
                  f"{c[False, True]} / {c[False, True] + c[False, False]} |")
    print(f"\n**All: demonstrator key {tot[True, True]} / {tot[True, True] + tot[True, False]} read back; "
          f"other key {tot[False, True]} / {tot[False, True] + tot[False, False]}.**")


if __name__ == "__main__":
    main()
