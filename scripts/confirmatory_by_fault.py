"""Per-fault VSC and post-ack refund check on the confirmatory splits (test_iid_c + test_ood_fault_c, n = 400), seeds
pooled where two exist. Shows where the +20 pp over the tool-trusting reward comes from. CPU.

    python scripts/confirmatory_by_fault.py > results/a4/confirmatory_by_fault.md
"""
import glob
import json
from collections import defaultdict

from actionproof.eval.by_fault import post_ack_check

ARMS = {"warm start": "rft_tiny_v2", "tool_trust": "grpo_tiny_v2_tool_trust_s*", "outcome": "grpo_tiny_v2_outcome_s*",
        "PCSTR-d": "grpo_tiny_v2_pcstr_d_s*"}
D = {}
for name, pat in ARMS.items():
    g = defaultdict(lambda: [0, 0.0, 0])  # n, vsc, post-ack check
    files = sorted(glob.glob(f"results/eval/conf/{pat}__neutral__test_*_c.jsonl"))
    for f in files:
        for l in open(f):
            e = json.loads(l)
            for k in ("+".join(e.get("faults") or []) or "benign", "ALL"):
                g[k][0] += 1; g[k][1] += e["vsc"]; g[k][2] += post_ack_check(e["trace"])
    D[name] = (len(files) // 2, g)
faults = sorted({k for _, g in D.values() for k in g}, key=lambda k: (k == "ALL", k))
print("# Confirmatory splits by fault\n\nGenerated by `scripts/confirmatory_by_fault.py` from `results/eval/conf/*_c.jsonl` "
      "(test_iid_c + test_ood_fault_c, 400 tasks per seed; seeds pooled: "
      + ", ".join(f"{n} {s}" for n, (s, _) in D.items()) + ").\n\nVSC (post-ack refund check rate in brackets). "
      "PCSTR-d − tool_trust is in percentage points of VSC.\n")
print("| fault | tasks/seed | " + " | ".join(D) + " | PCSTR-d − tool_trust |\n|---" * 1 + "|---" * (len(D) + 2) + "|")
for k in faults:
    cells, v = [], {}
    for name, (s, g) in D.items():
        n, vs, pc = g[k]
        v[name] = vs / n if n else 0
        cells.append(f"{vs / n:.2f} ({pc / n:.2f})" if n else "–")
    n0 = D["PCSTR-d"][1][k][0] // D["PCSTR-d"][0]
    print(f"| {k} | {n0} | " + " | ".join(cells) + f" | {100 * (v['PCSTR-d'] - v['tool_trust']):+.1f} |")
