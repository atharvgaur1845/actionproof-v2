"""research_audit/MASTER_EXPERIMENT_LEDGER.md, generated from claims/claims.yaml, results/canonical/results.json and
the registration files. Every row is a ledger claim or a registration; nothing is typed by hand.

    python scripts/audit/master_ledger.py

Category rules (exactly one per row, never combined):
- REGISTERED_CONFIRMATORY: registered (a frozen PREREGISTRATION_*), primary family. Outcome column says supported or not.
- REGISTERED_SECONDARY: registered, and the claim's statement calls it secondary.
- EXPLORATORY: registered after results were seen, or descriptive without a registration.
- DEVELOPMENT: a candidate method's development result (a non-PREREGISTRATION design document).
- FAILED: a candidate dropped by its own pre-set criterion.
- INCOMPLETE: a registered study whose summary file does not exist.
- NOT_RUN: a registration with no claim and no result file.
Fields the ledger does not record (model, seeds, CI type for older claims) are written "see registration", never guessed.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]


def category(c: dict, label: str) -> str:
    st = (c.get("statement") or "").lower()
    if label == "failed":
        return "FAILED"
    if label == "incomplete":
        return "INCOMPLETE"
    if label == "future":
        return "NOT_RUN"
    if label == "development":
        return "DEVELOPMENT"
    if label in ("exploratory", "descriptive"):
        return "EXPLORATORY"
    if "secondary" in st and "primary" not in st:
        return "REGISTERED_SECONDARY"
    return "REGISTERED_CONFIRMATORY"


def main() -> None:
    cfg = yaml.safe_load((ROOT / "claims/claims.yaml").read_text())
    can = json.loads((ROOT / "results/canonical/results.json").read_text())
    labels = {c["id"]: c["label"] for c in can["claims"]}
    metrics: dict = {}
    for m in can["metrics"]:
        metrics.setdefault(m["claim"], []).append(m)
    rows, seen_regs = [], set()
    for c in cfg["claims"]:
        pre = c.get("prereg")
        pres = pre if isinstance(pre, list) else [pre] if pre else []
        seen_regs.update(p for p in pres if p)
        lab = labels.get(c["id"], "?")
        ms = metrics.get(c["id"], [])
        ok = sum(m["match"] for m in ms)
        frozen = []
        for p in pres:
            if p and str(p).startswith("PREREGISTRATION"):
                tag = p.replace("PREREGISTRATION", "").replace(".md", "").lower().lstrip("_")
                hf = sorted(ROOT.glob(f"results/{tag.replace('_', '')}*_hashes.json")) or sorted(ROOT.glob(f"results/{tag}*_hashes.json"))
                frozen.append("frozen" if hf else "not frozen")
        out = "supported" if c["status"] == "supported" else c["status"].replace("_", " ")
        meta = lambda k: next((m[k] for m in ms if m.get(k) not in (None, "not_recorded")), "see registration")
        rows.append([c["id"], re.sub(r"\s+", " ", c.get("statement") or "")[:220].replace("|", "/"),
                     ", ".join(map(str, pres)) or "none", ", ".join(frozen) or "—", category(c, lab), out,
                     ", ".join(c.get("eval") or []) or "—", c.get("stats") or "—", meta("model"), meta("seeds"),
                     meta("tasks"), meta("ci_type"),
                     f"{ok}/{len(ms)} numbers re-read and match" if ms else "no numbers",
                     "; ".join(c.get("deviations") or []) [:160].replace("|", "/") or "none"])
    for s, v in can["studies"].items():
        if v["label"] == "incomplete":
            rows.append([s, "registered study", v["registration"], "frozen", "INCOMPLETE", "summary missing", v["summary"], "—",
                         "see registration", "see registration", "see registration", "see registration", "—", "—"])
    regs = sorted(p.name for p in ROOT.glob("PREREGISTRATION*.md"))
    unclaimed = [r for r in regs if r not in seen_regs]
    hdr = ["ID", "Hypothesis or statement (ledger text)", "Registration", "Frozen", "Category", "Outcome", "Result file(s)",
           "Statistics script", "Model", "Seeds", "Tasks", "Interval type", "Reproduction (re-read from file)", "Deviations"]
    L = ["# Master experiment ledger (generated by `scripts/audit/master_ledger.py`; do not edit)", "",
         f"Sources: `claims/claims.yaml` ({len(cfg['claims'])} claims), `results/canonical/results.json` (content sha "
         f"{can['content_sha256'][:12]}), {len(regs)} registration files. Every number in a claim is re-read from its result file; "
         f"{sum(m['match'] for m in can['metrics'])} of {len(can['metrics'])} match.", "",
         "Columns the brief asks for that the ledger does not record per claim (initialisation, reward, algorithm, checkpoint, "
         "evaluation seeds) are fixed in each registration and are not repeated here. \"see registration\" means exactly that.", "",
         "## Counts by category", ""]
    cnt: dict = {}
    for r in rows:
        cnt[r[4]] = cnt.get(r[4], 0) + 1
    L += [f"- {k}: {v}" for k, v in sorted(cnt.items())] + ["", "## Claims", "",
          "| " + " | ".join(hdr) + " |", "|" + "---|" * len(hdr)]
    L += ["| " + " | ".join(map(str, r)) + " |" for r in rows]
    L += ["", f"## Registrations with no ledger claim ({len(unclaimed)})", "",
          "Each has a stated reason below. A registration without a reason is flagged for review.", ""]
    NOTES = {
        "PREREGISTRATION_A5.md": "Stage 1, frozen (results/a5_hashes.json). Results in results/eval/a5/ and the Stage 1 report; not carried into the Stage 2 claim ledger, and no current headline depends on them.",
        "PREREGISTRATION_A6.md": "Stage 1, frozen (results/a6_hashes.json); same as A5.",
        "PREREGISTRATION_A7.md": "Stage 1, frozen (results/a7_hashes.json); same as A5.",
        "PREREGISTRATION_A10.md": "Stage 1 strict-metric amendment; reported through claim S1-STRESS under its addendum.",
        "PREREGISTRATION_A8_ADDENDUM.md": "Placebo control for X1; reported with claim S1-A8.",
        "PREREGISTRATION_A8_ADDENDUM2.md": "X1 state cell; reported with claim S1-A8.",
        "PREREGISTRATION_AD_C1.md": "AD-C1 confirmatory study; tracked as a registered study (see the INCOMPLETE row or its claim once c1_summary.json exists).",
        "PREREGISTRATION_AD_C1_ADDENDUM1.md": "Part of AD-C1.",
        "PREREGISTRATION_AD_C1_NOTE2.md": "Part of AD-C1 (arm entry rule).",
        "PREREGISTRATION_AD_C1_NOTE3.md": "Part of AD-C1 (D3 seeds 2-4 not queued).",
        "PREREGISTRATION_J2.md": "Run and analysed (results/j2/j2_summary.json); numbers appear under claim PAPER-V3. **Gap: no claim of its own with its registered verdicts.**",
        "PREREGISTRATION_S3_ADDENDUM3.md": "Withdrawn before training as a degenerate design (write-up §22).",
    }
    L += [f"- `{r}`: {NOTES.get(r, '**no note: needs review**')}" for r in unclaimed]
    (ROOT / "research_audit/MASTER_EXPERIMENT_LEDGER.md").write_text("\n".join(L) + "\n")
    print(cnt, "unclaimed", len(unclaimed))


if __name__ == "__main__":
    main()
