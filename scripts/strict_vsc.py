"""Amendment 10 §1: strict verified completion (SVC) = VSC and no collateral write (a4_metrics.collateral, the CMR
definition), on the confirmatory splits and v2 test-IID. Receipts rebuilt from committed write attempts. CPU.

    python scripts/strict_vsc.py > results/a10/strict_vsc.md
"""
import glob
import json
import random
from collections import Counter

from actionproof.bench.generator import make_split
from actionproof.eval.a4_metrics import collateral

TASKS = {}


def goal(split, tid):
    if split not in TASKS:
        TASKS[split] = {t.task_id: t.goal for t in make_split(split)}
    g = TASKS[split][tid]
    return {"allowed_entities": list(g.allowed_entities), "required_writes": [list(w) for w in g.required_writes],
            "feasible": g.feasible}


def score(path, split):
    out, why = {}, Counter()
    for l in open(path):
        e = json.loads(l)
        rec = {"goal": goal(split, e["task_id"]),
               "receipts": [{"op": a["op"], "entity": a["entity"]} for a in e.get("attempts", []) if a.get("committed")]}
        c = collateral(rec)
        for x in set(c):
            why[x.split(":")[0] + ":" + x.split(":")[1] if ":" in x else x] += 1
        out[e["task_id"]] = (e["vsc"], int(e["vsc"] and not c))
    return out, why


ARMS = {"warm start": "rft_tiny_v2", "tool_trust": "grpo_tiny_v2_tool_trust_s{s}", "outcome": "grpo_tiny_v2_outcome_s{s}",
        "PCSTR-d": "grpo_tiny_v2_pcstr_d_s{s}"}
print("# Strict verified completion (Amendment 10 §1)\n\nGenerated by `scripts/strict_vsc.py`. SVC = VSC and no collateral "
      "write (CMR definition). Receipts rebuilt from committed write attempts.\n\n## Confirmatory splits (test_iid_c + test_ood_fault_c, 400 tasks)\n")
print("| arm | seeds | VSC | SVC | VSC − SVC | collateral writes seen (episodes) |\n|---|---|---|---|---|---|")
per = {}
for name, pat in ARMS.items():
    seeds = [0] if "{s}" not in pat else [0, 1]
    v = s = n = 0; why = Counter(); per[name] = {}
    for sd in seeds:
        for sp in ("test_iid_c", "test_ood_fault_c"):
            o, w = score(f"results/eval/conf/{pat.format(s=sd)}__neutral__{sp}.jsonl", sp)
            why += w
            for t, (a, b) in o.items():
                per[name].setdefault(t, []).append((a, b)); v += a; s += b; n += 1
    print(f"| {name} | {len(seeds)} | {v / n:.4f} | {s / n:.4f} | {100 * (v - s) / n:+.2f} pp | "
          + (", ".join(f"{k} {c}" for k, c in why.most_common(4)) or "none") + " |")
ts = sorted(per["PCSTR-d"])
m = lambda arm, t, i: sum(x[i] for x in per[arm][t]) / len(per[arm][t])
for i, lab in ((0, "VSC"), (1, "SVC")):
    d = lambda S: sum(m("PCSTR-d", t, i) - m("tool_trust", t, i) for t in S) / len(S)
    rng = random.Random(0)
    bs = sorted(d([rng.choice(ts) for _ in ts]) for _ in range(10_000))
    print(f"\nPCSTR-d − tool_trust on {lab}: {100 * d(ts):+.2f} pp, paired task bootstrap 95% CI [{100 * bs[250]:+.1f}, {100 * bs[9750]:+.1f}] (n = {len(ts)})")
print("\n## v2 test-IID (n = 200 per seed)\n\n| run | VSC | SVC |\n|---|---|---|")
for f in sorted(glob.glob("results/eval/r3/*__neutral__test_iid.jsonl")):
    o, _ = score(f, "test_iid")
    print(f"| {f.split('/')[-1].split('__')[0]} | {sum(a for a, _ in o.values()) / len(o):.3f} | {sum(b for _, b in o.values()) / len(o):.3f} |")
