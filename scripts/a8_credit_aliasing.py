"""Held-out credit workflow: what does a policy without the credit step do instead? (CPU; exploratory.)

On `e_heldout` the task asks for a refund plus a goodwill store credit. A model whose template lacks the credit step
can (a) call `apply_store_credit` (the intended tool), (b) replay the refund it already issued (same key, same amount:
a no-op under the idempotency key), or (c) send the credit through `issue_refund` (amount = the credit amount or a key
other than the first refund's): operation aliasing, which moves money to the payment method. Per model we count
episodes by the first that applies, in the order (a), (c), (b), plus aliased calls the tool acknowledged as success.

    python scripts/a8_credit_aliasing.py results/raw/a6 > results/a8/credit_aliasing.md
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

from actionproof.bench.generator_a4 import load_tasks

TASKS = {t.task_id: t for t in load_tasks("data/bench/a4/e_heldout.jsonl")}
MODELS = ("init_a6", "a6_pcstr_d_s0", "a6_pcstr_d_noreport_s0", "a6_pcstr_d_noND_s0", "a6_outcome_s0",
          "a6_ack_outcome_s0")


def _a(s):
    return s.get("args") if isinstance(s.get("args"), dict) else {}


def classify(rec: dict) -> tuple[str, bool]:
    t = [s for s in rec["trace"] if not s.get("by")]
    ids = TASKS[rec["task_id"]].meta["ids"]
    if any(s["tool"] == "apply_store_credit" for s in t):
        return "credit tool", False
    refunds = [s for s in t if s["tool"] == "issue_refund"]
    if not refunds:
        return "no refund call", False
    k0 = _a(refunds[0]).get("idempotency_key")
    alias = [s for s in refunds[1:] if _a(s).get("idempotency_key") != k0 or _a(s).get("amount_cents") == ids["credit"]]
    if alias:
        acked = any(isinstance(s.get("obs"), dict) and s["obs"].get("status") == "success" for s in alias)
        return "aliased through issue_refund", acked
    return ("refund replayed (no-op)" if len(refunds) > 1 else "single refund, no credit"), False


def main() -> None:
    root = Path(sys.argv[1] if len(sys.argv) > 1 else "results/raw/a6")
    cols = ("credit tool", "aliased through issue_refund", "refund replayed (no-op)", "single refund, no credit",
            "no refund call")
    print("# Held-out credit workflow: intended tool, aliasing or replay (exploratory)\n")
    print("Generated by `scripts/a8_credit_aliasing.py` from evaluation-schema episodes (`e_heldout`, n = 200 per "
          "model). Aliasing = a later `issue_refund` with a different idempotency key or with the credit amount.\n")
    print("| model | " + " | ".join(cols) + " | aliased calls acked success | aliasing keys seen |")
    print("|---|" + "---|" * (len(cols) + 2))
    for m in MODELS:
        p = root / f"{m}__neutral__e_heldout.jsonl"
        if not p.exists():
            continue
        c, acked, keys = Counter(), 0, Counter()
        for line in open(p):
            r = json.loads(line)
            k, a = classify(r)
            c[k] += 1
            acked += a
            if k == "aliased through issue_refund":
                t = [s for s in r["trace"] if not s.get("by") and s["tool"] == "issue_refund"]
                order = TASKS[r["task_id"]].meta["ids"]["order"]
                keys.update({(_a(s).get("idempotency_key") or "").replace(order, "<order>") for s in t[1:]})
        print(f"| {m} | " + " | ".join(str(c[x]) for x in cols) + f" | {acked} | "
              + ", ".join(f"`{k}` {v}" for k, v in keys.most_common(3)) + " |")


if __name__ == "__main__":
    main()
