"""Generated tables for docs/quality/PERFORMANCE_DIAGNOSIS.md, from results/quality/diagnosis_p1_{dev,test}.json
(`scripts/diagnose_failures.py`). Writes docs/quality/diagnosis_tables.md; the diagnosis text cites these tables and
adds no number of its own.

    python scripts/diagnosis_report.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STAGES = ["clean", "resolved", "no_read", "read_no_problem_shown", "read_not_acted", "acted_not_resolved",
          "resolved_other_step_failed", "never_commit_honest", "never_commit_not_honest"]
SPLITS = ["p1_test_full", "p1_test_pp", "p1_test_rec", "p1_test_wf4", "p1_test_combo"]


def pct(a, n):
    return f"{a / n:.3f}" if n else "—"


def stage_table(d: dict, arms: list[str], mode: str) -> str:
    rows = ["| Stage (share of episodes) | " + " | ".join(arms) + " |", "|---|" + "---|" * len(arms)]
    for s in STAGES:
        rows.append(f"| {s} | " + " | ".join(pct(d[f'{a}|{mode}|ALL']['stage'].get(s, 0), d[f'{a}|{mode}|ALL']['episodes'])
                                          for a in arms) + " |")
    for r in ("truthful", "false_success", "under_claim", "no_report"):
        rows.append(f"| report: {r} | " + " | ".join(pct(d[f'{a}|{mode}|ALL']['report'].get(r, 0), d[f'{a}|{mode}|ALL']['episodes'])
                                                 for a in arms) + " |")
    rows.append("| VSC | " + " | ".join(f"{d[f'{a}|{mode}|ALL']['vsc']:.3f}" for a in arms) + " |")
    rows.append("| episodes | " + " | ".join(str(d[f'{a}|{mode}|ALL']['episodes']) for a in arms) + " |")
    return "\n".join(rows)


def cell_table(d: dict, arm: str, mode: str, top: int = 12) -> str:
    cells = [(k.split("|", 2)[2], v) for k, v in d.items() if k.startswith(f"{arm}|{mode}|") and "|split:" not in k and not k.endswith("|ALL")]
    cells.sort(key=lambda kv: -(kv[1]["episodes"] - kv[1]["vsc"] * kv[1]["episodes"]))
    rows = ["| Workflow · first fault | Episodes | VSC | no read | read, not acted | acted, not resolved | false success | new key on re-pay |",
            "|---|---|---|---|---|---|---|---|"]
    for k, v in cells[:top]:
        n, st, rp = v["episodes"], v["stage"], v["report"]
        nk = "—" if v["new_key_share_on_repay"] is None else f"{v['new_key_share_on_repay']:.2f}"
        rows.append(f"| {k.replace('|', ' · ')} | {n} | {v['vsc']:.2f} | {st.get('no_read', 0)} | {st.get('read_not_acted', 0)} | "
                    f"{st.get('acted_not_resolved', 0)} | {rp.get('false_success', 0)} | {nk} |")
    return "\n".join(rows)


def split_table(d: dict, arms: list[str], mode: str) -> str:
    rows = ["| Split | " + " | ".join(arms) + " |", "|---|" + "---|" * len(arms)]
    for sp in SPLITS:
        rows.append(f"| {sp} | " + " | ".join(f"{d[k]['vsc']:.3f}" if (k := f'{a}|{mode}|split:{sp}') in d else "—" for a in arms) + " |")
    return "\n".join(rows)


def main() -> None:
    out = ["# Diagnosis tables (generated by scripts/diagnosis_report.py; do not edit)", ""]
    for ph in ("dev", "test"):
        f = ROOT / f"results/quality/diagnosis_p1_{ph}.json"
        if not f.exists():
            continue
        d = json.loads(f.read_text())
        arms = sorted({k.split("|")[0] for k in d})
        for mode in ("sampled", "greedy"):
            n = {a: d[f"{a}|{mode}|ALL"]["episodes"] for a in arms}
            out += [f"## P1 {ph}, {mode}: failure stage of each episode", "",
                    f"Episodes per arm: {n}. Every arm pools its available seeds. An arm with fewer episodes has seeds still running.", "",
                    stage_table(d, arms, mode), ""]
            if ph == "test":
                out += [f"### P1 test, {mode}: VSC per split", "", split_table(d, arms, mode), ""]
        for a in ("A", "C"):
            if f"{a}|sampled|ALL" in d:
                out += [f"### P1 {ph}, arm {a}, sampled: the twelve cells with the most failures", "", cell_table(d, a, "sampled"), ""]
    p = ROOT / "docs/quality/diagnosis_tables.md"
    p.write_text("\n".join(out))
    print("wrote", p, len(out), "lines")


if __name__ == "__main__":
    main()
