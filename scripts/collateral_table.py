"""Collateral-modification rate (CMR: share of episodes with a write outside the task's allowed scope) next to VSC, for
every A6/A7/A8 model with a greedy evaluation summary. A separate safety dimension: PCSTR-d does not penalise an extra
write when the task goal is met (results/a4/hacking_ledger.md). CPU.

    python scripts/collateral_table.py > results/a6/collateral.md
"""
import glob
import json

SPLITS = ["test_iid", "test_ood_fault", "e_seen_refund", "e_seen_other", "e_heldout"]
print("# Collateral modifications next to verified success\n\nGenerated by `scripts/collateral_table.py` from "
      "`results/eval/a6/<run>__neutral__<split>.summary.json`. Cell: VSC / CMR (share of episodes with an out-of-scope "
      "write). Greedy, one seed per row.\n\n| run | " + " | ".join(SPLITS) + " |\n|---|" + "---|" * len(SPLITS))
runs = sorted({f.split("/")[-1].split("__")[0] for f in glob.glob("results/eval/a6/*__neutral__test_iid.summary.json")})
for r in runs:
    cells = []
    for s in SPLITS:
        try:
            d = json.load(open(f"results/eval/a6/{r}__neutral__{s}.summary.json"))
            cells.append(f"{d['vsc']:.2f} / {d['a4']['cmr']:.2f}")
        except (FileNotFoundError, KeyError):
            cells.append("–")
    print(f"| {r} | " + " | ".join(cells) + " |")
