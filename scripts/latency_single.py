"""Single-request latency (Track 3 "average latency"): each test_iid task run alone (batch 1, greedy) on vLLM, one
model loaded at a time. Wall-clock per episode and per model call; p50 / p95 / mean. Exploratory, not registered.

    python scripts/latency_single.py --n 100 --out results/latency_single.json
    python scripts/latency_single.py --report results/latency_single.json > results/latency_single.md
"""
import argparse
import json
import statistics
import time

MODELS = {"warm start (rft_tiny_v2)": None, "tool_trust s0": "runs/grpo_tiny_v2_tool_trust_s0/final",
          "PCSTR-d s0": "runs/grpo_tiny_v2_pcstr_d_s0/final"}
BASE = "CohereLabs/tiny-aya-global"


def pct(xs, q):
    xs = sorted(xs)
    return xs[min(len(xs) - 1, int(round(q * (len(xs) - 1))))]


def measure(n: int) -> dict:
    import subprocess
    import sys
    import tempfile
    out = {}
    for name in MODELS:
        with tempfile.NamedTemporaryFile(suffix=".json") as f:
            subprocess.run([sys.executable, __file__, "--n", str(n), "--one", name, "--out", f.name], check=True)
            out[name] = json.load(open(f.name))
    return out


def measure_one(name: str, n: int) -> list:
    from vllm import LLM
    from actionproof.bench.generator import make_split
    from actionproof.bench.prompts import NEUTRAL
    from actionproof.eval.run_eval import run
    from actionproof.train.merge import merge
    tasks = make_split("test_iid", n)
    ad = MODELS[name]
    w = merge(ad, BASE) if ad else merge("runs/rft_tiny_v2/final", BASE)
    llm = LLM(w, gpu_memory_utilization=0.85, max_model_len=8192, dtype="bfloat16", seed=0)
    run(llm, tasks[:2], NEUTRAL, 1, 0.0, 10, 256)  # warm-up, not timed
    eps = []
    for t in tasks:
        t0 = time.perf_counter()
        r = run(llm, [t], NEUTRAL, 1, 0.0, 10, 256)[0]
        dt = time.perf_counter() - t0
        eps.append({"task_id": t.task_id, "seconds": dt, "model_calls": r["turns"], "vsc": r["vsc"]})
    return eps


def report(d: dict) -> None:
    print("# Single-request latency (batch 1, greedy, one A100)\n\nGenerated by `scripts/latency_single.py`; each test_iid "
          "task run alone, model weights merged, after a 2-task warm-up. Exploratory.\n\n"
          "| model | episodes | p50 s / episode | p95 s / episode | mean s / episode | mean s / model call |\n|---|---|---|---|---|---|")
    for name, eps in d.items():
        s = [e["seconds"] for e in eps]
        per = sum(s) / sum(e["model_calls"] for e in eps)
        print(f"| {name} | {len(s)} | {pct(s, .5):.2f} | {pct(s, .95):.2f} | {statistics.mean(s):.2f} | {per:.3f} |")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=100)
    ap.add_argument("--out")
    ap.add_argument("--report")
    ap.add_argument("--one")
    a = ap.parse_args()
    if a.report:
        report(json.load(open(a.report)))
    elif a.one:
        json.dump(measure_one(a.one, a.n), open(a.out, "w"))
    else:
        json.dump(measure(a.n), open(a.out, "w"))
