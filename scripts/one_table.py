"""'If you only read one table': the v2 round, test-IID (n = 200, greedy) plus sampled read-back. CPU.

    python scripts/one_table.py > results/one_table.md
"""
import json

from actionproof.eval.a4_metrics import pwv

ARMS = [("Warm start (SFT, before RL)", "rft_tiny_v2", ["rft_tiny_v2"], "warm start"),
        ("Trusts the tool (tool_trust)", "ack", ["grpo_tiny_v2_tool_trust_s0", "grpo_tiny_v2_tool_trust_s1"], "tool_trust s0"),
        ("Acknowledgement outcome (ack_outcome)", "ack", ["grpo_tiny_v2_ack_outcome_s0", "grpo_tiny_v2_ack_outcome_s1"], "ack_outcome s0"),
        ("Database outcome (outcome)", "state", ["grpo_tiny_v2_outcome_s0", "grpo_tiny_v2_outcome_s1"], "outcome s0"),
        ("Database, PCSTR-d", "state", ["grpo_tiny_v2_pcstr_d_s0", "grpo_tiny_v2_pcstr_d_s1"], "PCSTR-d s0")]
F1 = {r["model"]: r for r in json.load(open("docs/figures/figures_data.json")) if r.get("figure") == "F1" and "sampled" in r["panel"]}
fmt = lambda xs, d=3: " / ".join(f"{x:.{d}f}".rstrip("0").rstrip(".") if x else "0" for x in xs)
print("# If you only read one table\n\nGenerated by `scripts/one_table.py`. Round v2: one warm start, one task band, 200 GRPO steps; "
      "only the reward differs. Test-IID, n = 200, greedy, one value per seed. Read-back = share of success-acknowledged refunds "
      "the agent reads back before moving on (greedy test-IID; sampled val, seed 0, in brackets).\n")
print("| reward | reward reads | test-IID VSC | false completion rate | refund read-back |\n|---|---|---|---|---|")
for name, ch, runs, f1 in ARMS:
    v, f, r = [], [], []
    for run in runs:
        s = json.load(open(f"results/eval/r3/{run}__neutral__test_iid.summary.json"))
        v.append(s["vsc"]); f.append(s["fcr"])
        eps = [json.loads(l) for l in open(f"results/eval/r3/{run}__neutral__test_iid.jsonl")]
        p = [x for x in (pwv(e["trace"], "issue_refund") for e in eps) if x is not None]
        r.append(sum(p) / len(p))
    src = {"rft_tiny_v2": "nothing (before RL)", "ack": "acknowledgements", "state": "database"}[ch]
    print(f"| {name} | {src} | {fmt(v)} | {fmt(f, 2)} | {fmt(r, 2)} ({F1[f1]['rate']:.2f}) |")
print("\nThe matched comparison is ack_outcome vs outcome: identical form (binary, same invariant mask), only the goal "
      "term's source differs.")
