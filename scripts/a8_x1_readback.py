"""Amendment 8 primary metric: greedy test_iid refund read-back (PWV_refund) for X1, placebo and control, plus the
registered paired task bootstrap of X1 - placebo (10k, seed 0). CPU.

    python scripts/a8_x1_readback.py > results/a8/x1_readback.md
"""
import json
import random

from actionproof.eval.a4_metrics import pwv

RUNS = {"control (task 412)": "a7_ack_outcome_s0", "placebo (414q)": "a8x1p_ack_outcome_s0", "X1 (414p)": "a8x1_ack_outcome_s0",
        "state arm s0 (411)": "a7_pcstr_d_noreport_s0"}
P = {}
print("# X1 / placebo refund read-back (Amendment 8)\n\nGenerated by `scripts/a8_x1_readback.py` from "
      "`results/eval/a6/<run>__neutral__test_iid.jsonl` (HF dataset actionproof-traces).\n\n| run | refund read-back |\n|---|---|")
for name, run in RUNS.items():
    recs = {json.loads(l)["task_id"]: json.loads(l) for l in open(f"results/eval/a6/{run}__neutral__test_iid.jsonl")}
    P[name] = {t: pwv(r["trace"], "issue_refund") for t, r in recs.items()}
    v = [x for x in P[name].values() if x is not None]
    print(f"| {name} | {sum(v)}/{len(v)} = {sum(v)/len(v):.3f} |")
pairs = [(P["X1 (414p)"][t], P["placebo (414q)"][t]) for t in P["X1 (414p)"]
         if P["X1 (414p)"][t] is not None and P["placebo (414q)"].get(t) is not None]
d = lambda ps: sum(a for a, _ in ps) / len(ps) - sum(b for _, b in ps) / len(ps)
rng = random.Random(0)
bs = sorted(d([rng.choice(pairs) for _ in pairs]) for _ in range(10_000))
print(f"\nX1 − placebo on {len(pairs)} paired tasks: {d(pairs):+.3f}, 95% CI [{bs[250]:.3f}, {bs[9750]:.3f}]")
