"""Amendment 10 §2 (offline): dependency-aware PCSTR-d. In these workflows every other required write depends on the
refund, so when a required refund did not fully commit (never committed, or committed partially), P and V are set to 0:
no partial credit for steps downstream of a failed prerequisite. Otherwise identical to PCSTR-d. Escalation and the
report terms are untouched. Simplification: only refund-rooted workflows are modelled. CPU.

    python scripts/a10_dep_reward.py UR_FILES... -- G1_FILES... > results/a10/dep_reward.md
"""
import json
import statistics
import sys
from collections import defaultdict
from types import SimpleNamespace

from actionproof.rewards import a6_rewards as A6
from actionproof.rewards.pcstr import pcstr_score

sys.path.insert(0, "scripts")
from a8_ur_rewards import behaviour  # noqa: E402  same behaviour classes as results/a8/ur_rewards.md


def refund_ok(r: dict) -> bool:
    att = [a for a in r.get("attempts", []) if a["op"] == "issue_refund"]
    if not att:
        return True  # no refund in this task
    return any(a["committed"] and a.get("fault") != "F3_partial" for a in att)


def dep_score(r: dict) -> float:
    v = dict(r["verdict"])
    if not refund_ok(r):
        v["P"], v["V"] = 0.0, 0.0
    return pcstr_score(SimpleNamespace(**v), disclosure=True)


def main() -> None:
    args = sys.argv[1:]
    cut = args.index("--")
    ur, g1 = args[:cut], args[cut + 1:]
    cells = defaultdict(list)
    for p in ur:
        for line in open(p):
            r = json.loads(line)
            b = behaviour(r)
            if b:
                cells[b].append(r)
    print("# Dependency-aware reward, offline (Amendment 10 §2)\n\nGenerated by `scripts/a10_dep_reward.py`; same "
          "unrecoverable-refund episodes and behaviour classes as `results/a8/ur_rewards.md`. G = 0 in every episode.\n")
    print("| behaviour | episodes | PCSTR-d | A7 state arm (noreport) | dependency-aware PCSTR-d |\n|---|---|---|---|---|")
    for b in sorted(cells):
        rs = cells[b]
        vs = [SimpleNamespace(**r["verdict"]) for r in rs]
        print(f"| {b} | {len(rs)} | {statistics.mean(pcstr_score(v, disclosure=True) for v in vs):+.3f} | "
              f"{statistics.mean(A6.pcstr_d_noreport_score(v) for v in vs):+.3f} | {statistics.mean(dep_score(r) for r in rs):+.3f} |")
    n = diff = 0
    for p in g1:
        for line in open(p):
            r = json.loads(line)
            if r["verdict"]["G"] == 1:
                n += 1
                diff += abs(dep_score(r) - pcstr_score(SimpleNamespace(**r["verdict"]), disclosure=True)) > 1e-9
    print(f"\nH-A10d: on {n} episodes with G = 1 (files: {len(g1)}), dependency-aware PCSTR-d differs from PCSTR-d in {diff}.")


if __name__ == "__main__":
    main()
