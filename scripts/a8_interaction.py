"""Amendment 8 addendum 2: channel x pool interaction on greedy test_iid refund read-back (PWV_refund).

(X1 ack - control ack) - (X1 state - full-pool state s0), paired task bootstrap (10k, seed 0) over tasks present in all
four runs. Also the A7 acknowledgement arm at seed 1 next to seed 0. CPU.

    python scripts/a8_interaction.py > results/a8/x1_interaction.md
"""
import json
import random
from pathlib import Path

from actionproof.eval.a4_metrics import pwv

RUNS = {"ack, full pool (412)": "a7_ack_outcome_s0", "ack, X1 pool (414p)": "a8x1_ack_outcome_s0",
        "state, full pool (411)": "a7_pcstr_d_noreport_s0", "state, X1 pool (417)": "a8x1s_pcstr_d_noreport_s0",
        "ack, full pool, seed 1 (418)": "a7_ack_outcome_s1", "state, full pool, seed 1 (415)": "a7_pcstr_d_noreport_s1"}
P = {}
print("# X1 channel x pool interaction (Amendment 8 addendum 2)\n\nGenerated by `scripts/a8_interaction.py` from "
      "`results/eval/a6/<run>__neutral__test_iid.jsonl`.\n\n| run | refund read-back |\n|---|---|")
for name, run in RUNS.items():
    f = Path(f"results/eval/a6/{run}__neutral__test_iid.jsonl")
    if not f.exists():
        print(f"| {name} | not run |")
        continue
    P[name] = {json.loads(l)["task_id"]: pwv(json.loads(l)["trace"], "issue_refund") for l in f.open()}
    v = [x for x in P[name].values() if x is not None]
    print(f"| {name} | {sum(v)}/{len(v)} = {sum(v)/len(v):.3f} |")
k = ["ack, X1 pool (414p)", "ack, full pool (412)", "state, X1 pool (417)", "state, full pool (411)"]
if all(x in P for x in k):
    ts = [t for t in P[k[0]] if all(P[x].get(t) is not None for x in k)]
    m = lambda x, s: sum(P[x][t] for t in s) / len(s)
    f = lambda s: (m(k[0], s) - m(k[1], s)) - (m(k[2], s) - m(k[3], s))
    rng = random.Random(0)
    bs = sorted(f([rng.choice(ts) for _ in ts]) for _ in range(10_000))
    print(f"\nInteraction (ack pool effect − state pool effect) on {len(ts)} tasks: {f(ts):+.3f}, "
          f"95% CI [{bs[250]:.3f}, {bs[9750]:.3f}]")
