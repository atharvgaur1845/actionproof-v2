"""Impact projection from the locked TXN benchmark (descriptive; no registration). Every rate is MEASURED on
txn_test (440 tasks; results/txn/*__txn_test.summary.json, and results/sel1/*__txn_test.summary.json when present);
every dollar figure is a PROJECTION from the assumption brackets of docs/upgrade/ROI.md §3. No real deployment exists
and nothing here is an observed saving.

Unit: 1,000 workflows that meet an ambiguous-execution fault of TXN's mix (TXN's tasks are fault-enriched by design;
each TXN episode stands for one such workflow). Per workflow:
- false completion (FCR; reported done, not done): exception cost x late-discovery multiplier;
- duplicate mutation (DMR): value x (1 - recovery rate) + exception cost x multiplier;
- false compensation (FCompR; a committed payment refunded): exception cost x multiplier;
- every other episode that is not a verified completion (failed report, escalation, stall): exception cost (a person
  sees it at once). Unnecessary retries are not charged separately: one that is not deduplicated is a duplicate.
Per 1,000 *all* workflows, multiply by the fault incidence f of the scenario. Clean workflows are assumed handled
correctly by every agent (an assumption: it favours the acknowledgement-trusting agent, which is right on them).

    python scripts/impact_txn.py   # writes results/impact/impact_txn.json and .md
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCEN = {  # docs/upgrade/ROI.md §3 (sources and quality there)
    "conservative": {"f": 0.005, "value": 2000, "exception": 25, "mult": 2, "recovery": 0.70},
    "moderate": {"f": 0.02, "value": 5000, "exception": 60, "mult": 3, "recovery": 0.60},
    "optimistic": {"f": 0.05, "value": 10000, "exception": 175, "mult": 5, "recovery": 0.50},
}
AGENTS = {  # label -> tags (seed models averaged; the range over seeds is reported)
    "B0 trust the acknowledgement (scripted)": ["B0"],
    "B1 final-state check only (scripted)": ["B1"],
    "B3 bounded retry + idempotency key (scripted)": ["B3"],
    "W plain SFT warm start (Tiny Aya Global)": ["W"],
    "Dw_aug randomised recovery SFT (3 seeds)": ["Dwaug_s0", "Dwaug_s1", "Dwaug_s2"],
    "D recovery SFT + GRPO (3 seeds)": ["D_s0", "D_s1", "D_s2"],
    "SEL1 CTL (3 seeds)": ["sel1:CTL_s0", "sel1:CTL_s1", "sel1:CTL_s2"],
    "SEL1 SEL (3 seeds)": ["sel1:SEL_s0", "sel1:SEL_s1", "sel1:SEL_s2"],
    "B4 transaction-aware reconciliation (scripted reference)": ["B4"],
}


def rates(tag: str) -> dict | None:
    d, t = ("sel1", tag[5:]) if tag.startswith("sel1:") else ("txn", tag)
    f = ROOT / f"results/{d}/{t}__txn_test.summary.json"
    if not f.exists():
        return None
    a = json.loads(f.read_text())["txn"]["all"]
    r = {k: a[k]["rate"] for k in ("VTC", "FCR", "DMR_all", "FCompR_all", "URR_all")}
    r.update(escalated=1 - a["coverage"]["rate"], episodes=a["n"], calls=a["cost"]["calls"])
    return r


def cost(r: dict, s: dict) -> float:
    e, m = s["exception"], s["mult"]
    other = max(0.0, 1 - r["VTC"] - r["FCR"])
    return 1000 * (r["FCR"] * e * m + r["DMR_all"] * (s["value"] * (1 - s["recovery"]) + e * m)
                   + r["FCompR_all"] * e * m + other * e)


def main() -> None:
    out = {"unit": "per 1,000 faulted workflows (TXN mix); x f for per 1,000 workflows", "scenarios": SCEN,
           "agents": {}}
    for label, tags in AGENTS.items():
        rs = [x for x in (rates(t) for t in tags) if x]
        if len(rs) != len(tags):
            continue
        mean = {k: sum(x[k] for x in rs) / len(rs) for k in rs[0]}
        row = {"tags": tags, "rates": mean, "projected_cost_per_1000_faulted": {}, "per_1000_workflows": {}}
        for name, s in SCEN.items():
            cs = [cost(x, s) for x in rs]
            row["projected_cost_per_1000_faulted"][name] = {"mean": sum(cs) / len(cs), "min": min(cs), "max": max(cs)}
            row["per_1000_workflows"][name] = s["f"] * sum(cs) / len(cs)
        out["agents"][label] = row
    d = ROOT / "results/impact"
    d.mkdir(parents=True, exist_ok=True)
    (d / "impact_txn.json").write_text(json.dumps(out, indent=1) + "\n")
    L = ["# Impact projection from TXN rates (generated by scripts/impact_txn.py)", "",
         "Rates measured on the locked txn_test (all episodes). Dollars are projections (docs/upgrade/ROI.md §3), "
         "per 1,000 workflows that meet an ambiguous-execution fault; per 1,000 of all workflows multiply by f.", "",
         "| Agent | VTC | False completion | Duplicate mutation | False refund | Escalated | Moderate ($) | Range over seeds | Conservative | Optimistic |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for label, row in out["agents"].items():
        r, c = row["rates"], row["projected_cost_per_1000_faulted"]
        L.append(f"| {label} | {r['VTC']:.3f} | {r['FCR']:.3f} | {r['DMR_all']:.3f} | {r['FCompR_all']:.3f} | "
                 f"{r['escalated']:.3f} | {c['moderate']['mean']:,.0f} | {c['moderate']['min']:,.0f}–{c['moderate']['max']:,.0f} | "
                 f"{c['conservative']['mean']:,.0f} | {c['optimistic']['mean']:,.0f} |")
    (d / "impact_txn.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
