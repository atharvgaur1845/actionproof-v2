"""Render recorded procurement episodes as full incident lifecycles for the write-up (docs/submission/TRACES.md).

Everything is read from the recorded evaluation files. Nothing is re-run or edited. For each episode the output shows:
- the initial database rows for the purchase order;
- the request;
- every tool call with the observation the agent received;
- the hidden fault injection for each write, which the agent never sees;
- the final database rows;
- the verifier's verdict.

    python scripts/writeup_traces.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EPISODES = [
    ("Failure: the agent reads the shortfall and still reports success",
     "results/s3/conf/s3_rv_mix_s0__s3_conf_full.jsonl", "s3_conf_full-0014",
     "Recovery-start GRPO, seed 0. Partial payment after a goods receipt: the cell that no training arm solves "
     "(ledger row 12)."),
    ("Success: detect, refund, re-pay, verify (rare)",
     "results/s3/conf/s3_rv_mix_s3__s3_conf_full.jsonl", "s3_conf_full-0052",
     "Recovery-start GRPO, seed 3. The same cell. This is one of the 5 repaired tasks out of 60 in this cell across "
     "the recovery-start runs (ledger row 12), so it is shown as a rare success, not a typical one."),
]
TABLES = ("pos", "payments", "receipts", "journal", "supplier_orders", "escalations")


def rows(state: dict, po: str) -> list[str]:
    out = []
    for t in TABLES:
        rs = [r for r in state.get(t, []) if r.get("po_id") == po]
        out.append(f"- `{t}`: " + (json.dumps(rs, ensure_ascii=False) if rs else "none"))
    return out


def render(title: str, path: str, task_id: str, note: str) -> str:
    rec = next(json.loads(line) for line in (ROOT / path).read_text().splitlines() if json.loads(line)["task_id"] == task_id)
    po = rec["task"]["meta"]["po_id"] if "meta" in rec["task"] else rec["task"].get("po_id")
    init = rec["task"].get("initial_state") or {}
    att = {a["idx"]: a for a in rec["attempts"]}
    s = rec["score"]
    L = [f"## {title}", "", f"Source: `{path}`, task `{task_id}` (model `{rec['tag']}`, fault class `{rec['fault_class']}`). {note}", "",
         "### 1. Initial state (purchase-order rows)"] + (rows(init, po) if init else ["- (initial state not stored in this record)"])
    L += ["", "### 2. Request", "", f"> {rec['task_prompt']}", "", "### 3. Episode",
          "", "| # | Agent call | What the agent received | Hidden: injected fault and what was stored |", "|---|---|---|---|"]
    for t in rec["trace"]:
        a = att.get(t["idx"])
        hid = f"`{a['fault'] or 'none'}`, stored: `{a['committed']}`" if a else ("(read: no fault)" if t["tool"] != "submit_report" else "")
        L.append(f"| {t['idx']} | `{t['tool']}({json.dumps(t['args'], ensure_ascii=False)})` | `{json.dumps(t['obs'], ensure_ascii=False)}` | {hid} |")
    L += ["", "### 4. Database after the episode"] + rows(rec["final_state"], po)
    L += ["", "### 5. Verifier verdict (authoritative)", "",
          f"- Per step: {', '.join(f'{k} → `{v}`' for k, v in s['steps'].items())}",
          f"- Goal met: **{s['goal_met']}**; verified completion (VSC): **{s['vsc']}**; false success: **{s['false_success']}**",
          f"- Reported by the agent: `{json.dumps(rec['report'], ensure_ascii=False)}`",
          f"- Reward the acknowledgement-based reward would give: R_A = {s['r_a']}; state-based reward: R_V = {s['r_v']}", ""]
    return "\n".join(L)


def main() -> None:
    out = ["# Recorded incident lifecycles (generated by `scripts/writeup_traces.py`; do not edit)", "",
           "Real recorded greedy evaluation episodes of frozen models on the confirmatory split `s3_conf_full`. "
           "The 'hidden' column comes from the simulator's fault log; the agent never sees it. "
           "The acknowledgement for a write is byte-identical whether the write stored everything, part, twice or nothing.", ""]
    out += [render(*e) for e in EPISODES]
    dest = ROOT / "docs/submission/TRACES.md"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(out))
    print(dest.relative_to(ROOT), len(out))


if __name__ == "__main__":
    main()
