"""Task 416b(1): unrecoverable tasks rolled out in the TRAINING schema (plain EcomEnv; SPEC §27 2026-11-13, P3).

Per model, split by the faulted tool: report status counts, and for refund-UR the stop-mode rate
(stop-mode = >= 3 refund attempts and the last ledger read before the report shows no refund; SPEC §27 2026-11-11 22:00)
and P(failed | stop-mode). Also: refund read-back (a4_metrics.pwv) and the H7-3 key marker.

    python scripts/a7_plain_ur.py results/eval/a7/plain > results/a7/plain_ur.md
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

from actionproof.eval.a4_metrics import pwv

MODELS = ("init", "a6_pcstr_d_s0", "a6_pcstr_d_s1", "a6_pcstr_d_noreport_s0", "a6_pcstr_d_noreport_s1",
          "a6_pcstr_d_noND_s0", "a6_pcstr_d_noFunder_s0", "a6_outcome_s0", "a6_ack_outcome_s0")


def _args(s):
    return s.get("args") if isinstance(s.get("args"), dict) else {}


def stop_mode(t: list[dict]) -> bool:
    refunds = [i for i, s in enumerate(t) if s["tool"] == "issue_refund"]
    reads = [s for s in t if s["tool"] == "query_ledger"]
    if len(refunds) < 3 or not reads:
        return False
    last = reads[-1].get("obs") or {}
    return not (last.get("refunds") if isinstance(last, dict) else None)


def main() -> None:
    root = Path(sys.argv[1] if len(sys.argv) > 1 else "results/eval/a7/plain")
    print("# Unrecoverable tasks in the training schema (task 416b, exploratory)\n")
    print("Generated by `scripts/a7_plain_ur.py`. Greedy, 18 turns, plain `EcomEnv`, training system prompt; "
          "100 non-credit `e_unrecoverable` tasks.\n")
    print("| model | refund-UR: failed / n | stop-mode / n | P(failed \\| stop-mode) | refund read back | "
          "demonstrator key | audit/close-UR: failed / n |")
    print("|---|---|---|---|---|---|---|")
    for m in MODELS:
        p = root / f"{m}__neutral__e_unrecoverable.jsonl"
        if not p.exists():
            print(f"| {m} | – | – | – | – | – | – |")
            continue
        c = Counter()
        for line in open(p):
            r = json.loads(line)
            t = [s for s in r["trace"] if not s.get("by")]
            refund = (r.get("a4") or {}).get("fault_tool") == "issue_refund"
            st = (r["verdict"].get("reported") or "none")
            if not refund:
                c["o_n"] += 1
                c["o_f"] += st == "failed"
                continue
            c["r_n"] += 1
            c["r_f"] += st == "failed"
            sm = stop_mode(t)
            c["sm"] += sm
            c["sm_f"] += sm and st == "failed"
            v = pwv(r["trace"], "issue_refund")
            c["pw"] += bool(v)
            ref = next((s for s in t if s["tool"] == "issue_refund"), None)
            c["key"] += bool(ref) and _args(ref).get("idempotency_key") == f"refund-{_args(ref).get('order_id')}"
        psm = f"{c['sm_f'] / c['sm']:.2f}" if c["sm"] else "–"
        print(f"| {m} | {c['r_f']} / {c['r_n']} | {c['sm']} / {c['r_n']} | {psm} | {c['pw']} / {c['r_n']} | "
              f"{c['key']} / {c['r_n']} | {c['o_f']} / {c['o_n']} |")


if __name__ == "__main__":
    main()
