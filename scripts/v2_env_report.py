import os

MODELS = {"warm start": ("rft_tiny_v2", "rft_tiny_v2"), "tool_trust s0": ("tool_trust_s0", "grpo_tiny_v2_tool_trust_s0"),
          "ack_outcome s0": ("ack_outcome_s0", "grpo_tiny_v2_ack_outcome_s0"), "outcome s0": ("outcome_s0", "grpo_tiny_v2_outcome_s0"),
          "PCSTR-d s0": ("pcstr_d_s0", "grpo_tiny_v2_pcstr_d_s0")}
print("# Existing policies in ActionProof-Bench v2 (Amendment 10 addendum)\n\nGenerated by `scripts/v2_env_report.py` from "
      "`results/eval/v2env/`. Greedy, neutral prompt, 12 turns. v2: idempotency scoped to (operation, entity, key); "
      "34 tasks copied with the timeout before the commit.\n")
print("| model | v1 test_iid VSC | v2, same 200 tasks | v2, timeout after commit (34) | v2, timeout before commit (34) |\n|---|---|---|---|---|")
for name, (tag, v1) in MODELS.items():
    f = f"results/eval/v2env/{tag}__neutral__test_iid_v2.jsonl"
    if not os.path.exists(f):
        print(f"| {name} | – | not finished | | |"); continue
    R = [json.loads(l) for l in open(f)]
    base = [r for r in R if not r["task_id"].endswith("_pre")]
    pre = [r for r in R if r["task_id"].endswith("_pre")]
    ids = {r["task_id"][:-4] for r in pre}
    post = [r for r in base if r["task_id"] in ids]
    m = lambda xs: f"{sum(r['vsc'] for r in xs) / len(xs):.3f}"
    v1s = json.load(open(f"results/eval/r3/{v1}__neutral__test_iid.summary.json"))["vsc"]
    print(f"| {name} | {v1s:.3f} | {m(base)} | {m(post)} | {m(pre)} |")
