"""Machine-readable experiment inventory and gap report (docs/upgrade/PLAN.md, W1).

Joins, from the files themselves:
- every `PREREGISTRATION_*.md`;
- the `results/*_hashes.json` file that freezes it, with its registration time;
- every `claims/claims.yaml` claim citing it, with its status and the files its numbers come from;
- whether each cited file exists.

Writes `results/inventory.json` and `docs/upgrade/INVENTORY.md`. Gaps are listed, not fixed: claims citing a
missing file, registrations no claim cites, and result folders that no registration freezes.

    python scripts/build_inventory.py
"""
from __future__ import annotations

import glob
import json
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def files_of(claim: dict) -> list[str]:
    out = []
    for v in (claim.get("numbers") or {}).values():
        f = v.get("file")
        out += f if isinstance(f, list) else [f]
    for k in ("eval", "runs"):
        out += [x for x in (claim.get(k) or []) if isinstance(x, str)]
    return sorted({x for x in out if x})


def main() -> None:
    claims = yaml.safe_load((ROOT / "claims/claims.yaml").read_text())["claims"]
    hashes = {}
    for h in sorted(glob.glob(str(ROOT / "results/*_hashes.json"))):
        d = json.loads(Path(h).read_text())
        for f in (d.get("files") or {}):
            if f.startswith("PREREGISTRATION"):
                hashes.setdefault(f, []).append({"hash_file": str(Path(h).relative_to(ROOT)), "registered": d.get("registered")})
    regs = []
    for p in sorted(ROOT.glob("PREREGISTRATION*.md")):
        title = p.read_text().splitlines()[0].lstrip("# ").strip()
        cl = [c for c in claims if c.get("prereg") == p.name or (isinstance(c.get("prereg"), list) and p.name in c["prereg"])]
        regs.append({
            "id": p.stem.replace("PREREGISTRATION_", "").replace("PREREGISTRATION", "MAIN"),
            "file": p.name, "title": title, "frozen_by": hashes.get(p.name, []),
            "claims": [{"id": c["id"], "status": c.get("status"),
                        "files": [{"path": f, "exists": (ROOT / f).exists() or bool(glob.glob(str(ROOT / f)))}
                                  for f in files_of(c)]} for c in cl],
        })
    cited = {f["path"] for r in regs for c in r["claims"] for f in c["files"]}
    result_dirs = sorted(d.name for d in (ROOT / "results").iterdir() if d.is_dir())
    frozen_tags = {re.sub(r"_hashes\.json$", "", Path(h).name) for h in glob.glob(str(ROOT / "results/*_hashes.json"))}
    gaps = {
        "claims_citing_missing_files": [(r["id"], c["id"], f["path"]) for r in regs for c in r["claims"] for f in c["files"]
                                        if not f["exists"]],
        "registrations_without_claims": [r["file"] for r in regs if not r["claims"]],
        "registrations_without_hash_file": [r["file"] for r in regs if not r["frozen_by"]],
        "result_dirs_not_cited_by_any_claim": [d for d in result_dirs if not any(p.startswith(f"results/{d}/") for p in cited)],
        "result_dirs_without_matching_hash_file": [d for d in result_dirs if d not in frozen_tags
                                                   and not any(t.startswith(d) for t in frozen_tags)],
    }
    status_counts: dict = {}
    for c in claims:
        status_counts[c.get("status")] = status_counts.get(c.get("status"), 0) + 1
    inv = {"registrations": regs, "claim_status_counts": status_counts, "gaps": gaps}
    (ROOT / "results/inventory.json").write_text(json.dumps(inv, indent=2))
    md = ["# Experiment inventory (generated by `scripts/build_inventory.py`; do not edit)", "",
          f"{len(regs)} registrations, {len(claims)} ledger claims. Claim status counts: "
          + ", ".join(f"{k} {v}" for k, v in sorted(status_counts.items(), key=lambda x: str(x[0]))) + ".", "",
          "| Registration | Frozen (time) | Claims (status) |", "|---|---|---|"]
    for r in regs:
        fr = "; ".join(f"`{x['hash_file']}` ({x['registered']})" for x in r["frozen_by"]) or "**not frozen**"
        cs = ", ".join(f"{c['id']} ({c['status']})" for c in r["claims"]) or "—"
        md.append(f"| `{r['file']}`: {r['title'][:70]} | {fr} | {cs} |")
    md += ["", "## Gaps", ""]
    for k, v in gaps.items():
        md.append(f"- **{k.replace('_', ' ')}** ({len(v)}): " + (", ".join(f"`{x}`" if isinstance(x, str) else
                                                                        "`" + " / ".join(x) + "`" for x in v) or "none"))
    (ROOT / "docs/upgrade/INVENTORY.md").write_text("\n".join(md) + "\n")
    print(json.dumps({k: len(v) for k, v in gaps.items()}), status_counts)


if __name__ == "__main__":
    main()
